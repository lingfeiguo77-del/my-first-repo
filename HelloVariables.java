public class HelloVariables {
    public static void main(String[] args) {
        // 名字：用 String 类型保存
        String name = "小明";
        // 年龄：用 int 类型保存
        int age = 18;
        // 学校：用 String 类型保存
        String school = "清华大学";

        System.out.println(name);
        System.out.println(age);
        System.out.println(school);
    }
}
